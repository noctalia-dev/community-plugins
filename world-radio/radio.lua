-- radio.lua
-- Bundled mpv helper for World Radio.
--
-- The panel launches mpv with the whole station queue as a playlist, which is
-- what lets mpv-mpris expose CanGoNext/CanGoPrevious and route Noctalia's
-- native media Next/Previous actions to the radio. This script keeps every
-- playlist entry labelled with its station name, applies that station's cached
-- cover art, and records the current playlist position in now.json so the
-- plugin's service can follow MPRIS-driven changes while the panel is closed.

local dataDir = os.getenv("WORLD_RADIO_DATA") or ""
local session = os.getenv("WORLD_RADIO_SESSION") or ""
local statePath = dataDir ~= "" and (dataDir .. "/now.json") or ""
local coversPath = dataDir ~= "" and (dataDir .. "/covers.txt") or ""
local songPath = dataDir ~= "" and (dataDir .. "/song.txt") or ""

local appliedCover = nil
local appliedSong = nil
local appliedTitle = nil
local stationName = ""

local function loadCovers()
  local list = {}
  if coversPath == "" then
    return list
  end
  local f = io.open(coversPath, "r")
  if f == nil then
    return list
  end
  for line in f:lines() do
    list[#list + 1] = line
  end
  f:close()
  return list
end

local function coverAt(list, pos)
  local cover = list[pos + 1]
  if cover == nil or cover == "-" then
    return ""
  end
  return cover
end

local function setCover(cover)
  if cover == appliedCover then
    return
  end
  appliedCover = cover
  pcall(function()
    mp.set_property("cover-art-files", cover)
  end)
end

local function writeNow(pos)
  if statePath == "" then
    return
  end
  -- The session token is generated by the panel and only ever contains safe
  -- characters; strip anything unexpected before embedding it in JSON.
  local safeSession = session:gsub('[%c"\\]', "")
  local tmp = statePath .. ".tmp"
  local f = io.open(tmp, "w")
  if f == nil then
    return
  end
  f:write(string.format('{"session":"%s","pos":%d}', safeSession, pos))
  f:close()
  -- Rename is atomic on POSIX, so the service never reads a partial file.
  os.rename(tmp, statePath)
end

-- The title shown by Noctalia's native media player comes from MPRIS, which
-- mpv-mpris builds from media-title. Show the song when the stream announces
-- one, and fall back to the station name (from #EXTINF) otherwise, so MPRIS
-- stays readable when the stream only advertises a generic "stream" title.
local function updateTitle()
  local title = stationName
  if appliedSong ~= nil and appliedSong ~= "" then
    title = appliedSong
  end
  if title == "" or title == appliedTitle then
    return
  end
  appliedTitle = title
  pcall(function()
    mp.set_property("force-media-title", title)
  end)
end

local function applyTrack()
  -- Reload instead of caching at startup: a local station's cover can be
  -- edited or found automatically while the playlist is already loaded.
  local covers = loadCovers()
  local pos = mp.get_property_number("playlist-pos", -1)
  if pos == nil or pos < 0 then
    return
  end
  stationName = mp.get_property("playlist/" .. tostring(pos) .. "/title", "") or ""
  updateTitle()
  setCover(coverAt(covers, pos))
end

-- Streams announce the current song in different ways depending on the
-- server: Shoutcast/Icecast send ICY metadata (icy-title / StreamTitle), while
-- Ogg/Opus, AAC and HLS streams put it in regular tags (title, artist). Local
-- radios are very often one of the latter, so look at every common key.
-- force-media-title hides the song from media-title, but the raw metadata
-- table keeps it, so mirror it to song.txt for the panel's mini player.
local function cleanValue(value)
  if value == nil then
    return ""
  end
  value = tostring(value):gsub("[%c]+", " "):gsub("^%s+", ""):gsub("%s+$", "")
  if #value > 200 then
    value = string.sub(value, 1, 200)
  end
  return value
end

local function metaGet(meta, wanted)
  for key, value in pairs(meta) do
    if type(key) == "string" and key:lower() == wanted then
      return cleanValue(value)
    end
  end
  return ""
end

local lastDump = nil

local function dumpMeta(meta)
  -- Debug aid: lists exactly what the stream advertises, so a station that
  -- shows no song can be diagnosed (cat ~/.local/share/.../meta-debug.txt).
  if dataDir == "" then
    return
  end
  local keys = {}
  for key, value in pairs(meta) do
    keys[#keys + 1] = tostring(key) .. " = " .. cleanValue(value)
  end
  table.sort(keys)
  local text = table.concat(keys, "\n")
  if text == lastDump then
    return
  end
  lastDump = text
  local f = io.open(dataDir .. "/meta-debug.txt", "w")
  if f ~= nil then
    f:write(text .. "\n")
    f:close()
  end
end

local function currentSong()
  local meta = mp.get_property_native("metadata")
  if type(meta) ~= "table" then
    return ""
  end
  dumpMeta(meta)

  local pos = mp.get_property_number("playlist-pos", -1)
  local station = ""
  if pos ~= nil and pos >= 0 then
    station = cleanValue(mp.get_property("playlist/" .. tostring(pos) .. "/title", ""))
  end

  local candidates = {
    metaGet(meta, "icy-title"),
    metaGet(meta, "streamtitle"),
  }
  local title = metaGet(meta, "title")
  local artist = metaGet(meta, "artist")
  if title ~= "" and artist ~= "" then
    candidates[#candidates + 1] = artist .. " - " .. title
  else
    candidates[#candidates + 1] = title
  end

  for _, value in ipairs(candidates) do
    -- A "title" equal to the station name is not a song.
    if value ~= "" and value ~= station then
      return value
    end
  end
  return ""
end

local function writeSong(value)
  if value == appliedSong then
    return
  end
  appliedSong = value
  updateTitle()
  if songPath == "" then
    return
  end
  local tmp = songPath .. ".tmp"
  local f = io.open(tmp, "w")
  if f == nil then
    return
  end
  f:write(value)
  f:close()
  os.rename(tmp, songPath)
end

mp.register_event("start-file", function()
  appliedSong = nil
  appliedTitle = nil
  applyTrack()
end)

mp.register_event("file-loaded", function()
  applyTrack()
  local pos = mp.get_property_number("playlist-pos", -1)
  if pos ~= nil and pos >= 0 then
    writeNow(pos)
  end
  writeSong(currentSong())
end)

-- Covers.txt is rewritten when a cover changes. Picking it up here also keeps
-- the next station correct even if mpv-mpris cached the old artwork.
mp.add_periodic_timer(1, function()
  local pos = mp.get_property_number("playlist-pos", -1)
  if pos == nil or pos < 0 then
    return
  end
  local cover = coverAt(loadCovers(), pos)
  if cover ~= appliedCover then
    setCover(cover)
  end
  writeSong(currentSong())
end)
