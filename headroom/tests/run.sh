#!/usr/bin/env bash
# Runs Headroom's Luau tests against the plugin sources, unmodified.
#
# The Luau CLI has no file I/O, so the plugin's sources, logos, fixtures,
# translations/en.json and plugin.toml are embedded into a generated module in
# a temp copy of tests/; tests/support/loader.luau then runs them the way
# Noctalia does, against a fake `noctalia` host.
#
# Usage: tests/run.sh   (needs `luau` on PATH, or LUAU=/path/to/luau)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
plugin="$(dirname "$here")"
luau="${LUAU:-$(command -v luau || true)}"
[[ -x "$luau" ]] || { echo "Luau CLI not found: put luau on PATH or set LUAU" >&2; exit 2; }
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
cp -r "$here" "$work/tests"
mkdir -p "$work/tests/_generated"
python3 -I - "$plugin" "$work/tests/_generated/sources.luau" <<'PY'
import pathlib, sys
root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
files = [p for p in root.rglob("*.luau") if p.relative_to(root).parts[0] != "tests"]
files += list(root.glob("providers/*/*.svg")) + list(root.glob("tests/fixtures/*.json"))
files += [root / "translations/en.json", root / "plugin.toml"]
def quote(text):
    level = 0
    while "]" + "=" * level + "]" in text:
        level += 1
    return f"[{'=' * level}[\n{text}]{'=' * level}]"
lines = ["-- Generated by tests/run.sh.", "return {"]
lines += [f'  ["{p.relative_to(root).as_posix()}"] = {quote(p.read_text())},' for p in sorted(files)]
out.write_text("\n".join(lines + ["}"]) + "\n")
PY
"$luau" "$work/tests/run.luau"
