#!/usr/bin/env bash
# Runs the Luau tests. Needs the Luau CLI: `luau` on PATH or LUAU=/path/to/luau.
#
# The CLI resolves require("./x") while Noctalia needs require("./x.luau"), and
# it has no file I/O. So the tests run from a temp copy: lib/ with the
# extension dropped from require paths (for the unit specs), plus the plugin's
# unmodified sources embedded as strings in _generated/sources.luau, which
# support/loader.luau runs the way Noctalia does (for the service spec).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
plugin="$(dirname "$here")"
luau="${LUAU:-$(command -v luau || true)}"
[[ -x "$luau" ]] || { echo "Luau CLI not found: put luau on PATH or set LUAU" >&2; exit 2; }
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
cp -r "$plugin/lib" "$here" "$work/"
find "$work/lib" "$work/tests" -name '*.luau' -exec sed -i -E 's/require\("([^"]+)\.luau"\)/require("\1")/' {} +
mkdir -p "$work/_generated"
python3 -I - "$plugin" "$work/_generated/sources.luau" <<'PY'
import pathlib, sys
root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
files = sorted(p for p in root.rglob("*.luau") if "tests" not in p.relative_to(root).parts)
files += sorted(root.glob("fixtures/*.json")) + [root / "translations/en.json"]
def quote(text):
    level = 0
    while "]" + "=" * level + "]" in text:
        level += 1
    return f"[{'=' * level}[\n{text}]{'=' * level}]"
lines = ["-- Generated by tests/run.sh.", "return {"]
lines += [f'  ["{p.relative_to(root).as_posix()}"] = {quote(p.read_text())},' for p in files]
out.write_text("\n".join(lines + ["}"]) + "\n")
PY
"$luau" "$work/tests/run.luau"
